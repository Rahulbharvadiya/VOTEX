"""Unit tests for sanitizer service."""

from votex_api.services.sanitizer import sanitize_payload, sanitize_text


def test_sanitize_secrets():
    text = "Authorization: Bearer my-secret-jwt-token-123456"
    sanitized = sanitize_text(text)
    assert "my-secret-jwt-token-123456" not in sanitized
    assert "***REDACTED***" in sanitized


def test_sanitize_vendor_branding():
    text = "Extracted text via Bodhan Indic-OCR and translated with Bodhan Indic-Translate."
    sanitized = sanitize_text(text)
    assert "Bodhan" not in sanitized
    assert "Indic-OCR" in sanitized
    assert "Indic-Translate" in sanitized


def test_sanitize_nested_payload():
    payload = {
        "user": {"api_key": "secret_key_abcdef123"},
        "notes": ["Generated by Bodhan AI", "Step 1 complete"],
    }
    cleaned = sanitize_payload(payload)
    assert "secret_key_abcdef123" not in str(cleaned)
    assert "Bodhan" not in str(cleaned)
    assert "VOTEX" in str(cleaned)
